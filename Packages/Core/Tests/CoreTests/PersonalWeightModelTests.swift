import XCTest
@testable import Core

final class PersonalWeightModelTests: XCTestCase {
    private let global = PhotoQualityScoringConfig.current

    // MARK: - Floor

    func testFewerThanMinimumExamplesLeavesEachBranchUnchanged() {
        let examples = (0..<9).map { makeExample(hasFaces: true, sharpnessDelta: 0.3, index: $0) }
            + (0..<9).map { makeExample(hasFaces: false, sharpnessDelta: 0.3, index: $0) }

        let result = PersonalWeightModel.personalWeights(from: examples, global: global)

        XCTAssertEqual(result.withFaces, global.weightsWithFaces)
        XCTAssertEqual(result.withoutFaces, global.weightsWithoutFaces)
    }

    // MARK: - Determinism

    func testSameInputTwiceIsBitIdentical() {
        let examples = (0..<40).map { makeExample(hasFaces: true, sharpnessDelta: 0.2, index: $0) }

        let first = PersonalWeightModel.personalWeights(from: examples, global: global)
        let second = PersonalWeightModel.personalWeights(from: examples, global: global)

        XCTAssertEqual(first.withFaces, second.withFaces)
        XCTAssertEqual(first.withoutFaces, second.withoutFaces)
    }

    // MARK: - Branch isolation

    func testFacelessExamplesDoNotAffectTheFacedBranch() {
        let facelessOnly = (0..<50).map { makeExample(hasFaces: false, sharpnessDelta: 0.3, index: $0) }

        let result = PersonalWeightModel.personalWeights(from: facelessOnly, global: global)

        // No faced examples were supplied, so that branch stays at the floor.
        XCTAssertEqual(result.withFaces, global.weightsWithFaces)
    }

    func testFacedExamplesDoNotAffectTheFacelessBranch() {
        let facedOnly = (0..<50).map { makeExample(hasFaces: true, sharpnessDelta: 0.3, index: $0) }

        let result = PersonalWeightModel.personalWeights(from: facedOnly, global: global)

        XCTAssertEqual(result.withoutFaces, global.weightsWithoutFaces)
    }

    // MARK: - Movement grows with n

    func testMovementFromGlobalGrowsWithExampleCount() {
        // Small, consistent deltas: large ones saturate the +-0.15 box by
        // n=30 already, which would make d30 and d200 equal rather than
        // strictly increasing. The shrinkage curve itself is what this test
        // is verifying, so the per-example signal must stay well inside the
        // box across the whole range.
        let n10 = (0..<10).map { movementExample(index: $0) }
        let n30 = (0..<30).map { movementExample(index: $0) }
        let n200 = (0..<200).map { movementExample(index: $0) }

        let d10 = distance(
            PersonalWeightModel.personalWeights(from: n10, global: global).withFaces,
            global.weightsWithFaces
        )
        let d30 = distance(
            PersonalWeightModel.personalWeights(from: n30, global: global).withFaces,
            global.weightsWithFaces
        )
        let d200 = distance(
            PersonalWeightModel.personalWeights(from: n200, global: global).withFaces,
            global.weightsWithFaces
        )

        XCTAssertLessThan(d10, d30)
        XCTAssertLessThan(d30, d200)
    }

    /// Regression for the gradient-averaging fix: summing the per-example
    /// likelihood gradient instead of averaging it let the likelihood term
    /// outweigh the ridge by a factor of n, so on realistic-magnitude data
    /// beta shot to 5-25x the global vector and every branch saturated the
    /// +-0.15 box — the fit became "box corner in the mean-delta direction,"
    /// throwing away signal strength entirely. `testMovementFromGlobalGrowsWithExampleCount`
    /// above only ever varies n at one (tiny) magnitude, so it could not
    /// catch that: a fit that ignores magnitude still passes when the only
    /// axis under test is example count. This test varies magnitude at a
    /// fixed n instead, and checks the fit is nowhere near the box.
    ///
    /// Deltas are component-wise uniform in the range implied by the
    /// coordinator's own measurement of the ranker's cluster-normalised
    /// components (roughly +-0.4 as "realistic"), generated by a seeded
    /// linear congruential generator so the fixture is deterministic without
    /// hardcoding a literal array.
    func testSignalStrengthMovesTheFitRatherThanJustSaturatingTheBox() {
        let direction = lcgUnitValues(count: 200 * 5, seed: 0x5EED_1234)

        for n in [30, 200] {
            let weak = (0..<n).map { signalExample(index: $0, direction: direction, magnitude: 0.1) }
            let realistic = (0..<n).map { signalExample(index: $0, direction: direction, magnitude: 0.4) }
            let strong = (0..<n).map { signalExample(index: $0, direction: direction, magnitude: 0.8) }

            let weakResult = PersonalWeightModel.personalWeights(from: weak, global: global).withFaces
            let realisticResult = PersonalWeightModel.personalWeights(from: realistic, global: global).withFaces
            let strongResult = PersonalWeightModel.personalWeights(from: strong, global: global).withFaces

            // Not a corner of the box: the realistic-magnitude fit at
            // realistic volumes is exactly the case that used to saturate.
            assertNoComponentPinnedToBoxEdge(realisticResult, global: global.weightsWithFaces, n: n)

            // Same n, only the magnitude of the evidence differs: a fit that
            // is sensitive to signal strength must move further for the
            // stronger signal. This is the assertion the old sum-not-mean
            // gradient would fail, since every magnitude collapsed onto the
            // same box corner once n was large enough.
            let weakDistance = distance(weakResult, global.weightsWithFaces)
            let realisticDistance = distance(realisticResult, global.weightsWithFaces)
            let strongDistance = distance(strongResult, global.weightsWithFaces)
            XCTAssertLessThan(weakDistance, realisticDistance, "n=\(n)")
            XCTAssertLessThan(realisticDistance, strongDistance, "n=\(n)")
        }
    }

    // MARK: - Hard constraints, including adversarial input

    func testOutputAlwaysSumsToOneAndIsNonNegative() {
        for examples in adversarialExampleSets() {
            let result = PersonalWeightModel.personalWeights(from: examples, global: global)
            assertValidWeights(result.withFaces, file: #filePath, line: #line)
            assertValidWeights(result.withoutFaces, file: #filePath, line: #line)
        }
    }

    func testEveryComponentStaysWithinPointOneFiveOfGlobal() {
        for examples in adversarialExampleSets() {
            let result = PersonalWeightModel.personalWeights(from: examples, global: global)
            assertWithinBox(result.withFaces, of: global.weightsWithFaces)
            assertWithinBox(result.withoutFaces, of: global.weightsWithoutFaces)
        }
    }

    func testWithoutFacesFaceQualityIsExactlyZero() {
        for examples in adversarialExampleSets() {
            let result = PersonalWeightModel.personalWeights(from: examples, global: global)
            XCTAssertEqual(result.withoutFaces.faceQuality, 0)
        }
    }

