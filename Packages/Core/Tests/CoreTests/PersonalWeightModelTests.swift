    // MARK: - The guardrail: weights only

    /// `personalWeights` returns a `(withFaces, withoutFaces)` pair of
    /// `Weights` — a five-component struct with no room for anything else.
    /// It physically cannot express a change to `absoluteSharpnessFloor`,
    /// the critical/strong/weak sharpness ratios or their penalties, the
    /// confidence thresholds, or any face-detection parameter. That matters:
    /// a blurred frame must never become Best Shot because of a few stray
    /// taps, and the only lever this model hands the user is how the five
    /// already-computed components are weighted against each other, never
    /// whether a frame clears the floor in the first place.
    func testReturnTypeCarriesWeightsOnlyNoThresholdsOrGates() {
        let examples = (0..<200).map { makeExample(hasFaces: true, sharpnessDelta: 0.3, index: $0) }

        let result = PersonalWeightModel.personalWeights(from: examples, global: global)

        // `Weights` has exactly these five stored properties (plus the
        // computed `total`); there is no field this assertion could miss
        // that would let a threshold or gate slip through the return type.
        _ = result.withFaces.sharpness
        _ = result.withFaces.faceQuality
        _ = result.withFaces.exposure
        _ = result.withFaces.noiseArtifacts
        _ = result.withFaces.resolution
        XCTAssertEqual(result.withFaces.total, 1, accuracy: 1e-9)

        // The un-personalised gates and floors are untouched by construction:
        // this call took no config beyond the global weights it started
        // from, and nothing it returns can be plugged back into
        // `absoluteSharpnessFloor` or any sharpness ratio.
        XCTAssertEqual(global.absoluteSharpnessFloor, PhotoQualityScoringConfig.current.absoluteSharpnessFloor)
    }

    // MARK: - Helpers

    /// A deterministic, seeded linear congruential generator, so a fixture
    /// spanning hundreds of examples does not have to be hand-typed while
    /// staying reproducible run to run (no `random`, no wall-clock seed).
    /// Values are in `[-1, 1]`; a caller scales by the desired magnitude.
    private func lcgUnitValues(count: Int, seed: UInt64) -> [Double] {
        var state = seed
        var values: [Double] = []
        values.reserveCapacity(count)
        for _ in 0..<count {
            state = state &* 6_364_136_223_846_793_005 &+ 1_442_695_040_888_963_407
            let normalized = Double(state >> 11) / Double(1 << 53)
            values.append(normalized * 2 - 1)
        }
        return values
    }

    /// One override example whose `componentDelta` is the `index`-th slice
    /// of `direction`, scaled by `magnitude`. Reusing the same `direction`
    /// across magnitudes isolates signal *strength* as the only variable
    /// between a weak, realistic and strong fixture built from it.
    private func signalExample(
        index: Int,
        direction: [Double],
        magnitude: Double
    ) -> BestShotOverrideExample {
        let base = index * 5
        return BestShotOverrideExample(
            recordedAt: Date(timeIntervalSince1970: Double(index)),
            clusterHasFaces: true,
            componentDelta: PhotoQualityScoringConfig.Weights(
                sharpness: direction[base] * magnitude,
                faceQuality: direction[base + 1] * magnitude,
                exposure: direction[base + 2] * magnitude,
                noiseArtifacts: direction[base + 3] * magnitude,
                resolution: direction[base + 4] * magnitude
            ),
            offsetDelta: 0,
            scoringModelVersion: global.scoringModelVersion
        )
    }

    /// Asserts no component sits at (or past) its `+-0.15` box edge — the
    /// signature of a fit that saturated instead of tracking the evidence.
    private func assertNoComponentPinnedToBoxEdge(
        _ weights: PhotoQualityScoringConfig.Weights,
        global: PhotoQualityScoringConfig.Weights,
        n: Int,
        file: StaticString = #filePath,
        line: UInt = #line
    ) {
        let margin = 0.01
        func assertNotPinned(_ value: Double, _ globalValue: Double, _ label: String) {
            XCTAssertLessThan(
                value, globalValue + 0.15 - margin,
                "\(label) pinned to the upper box edge at n=\(n)", file: file, line: line
            )
            // A component whose lower box edge falls below 0 is floored at
            // 0 by the >= 0 clamp before it could ever reach that edge, so
            // the lower-edge check only applies when the box itself allows
            // it — otherwise 0 is the floor, not evidence of saturation.
            if globalValue - 0.15 > 0 {
                XCTAssertGreaterThan(
                    value, globalValue - 0.15 + margin,
                    "\(label) pinned to the lower box edge at n=\(n)", file: file, line: line
                )
            }
        }
        assertNotPinned(weights.sharpness, global.sharpness, "sharpness")
        assertNotPinned(weights.faceQuality, global.faceQuality, "faceQuality")
        assertNotPinned(weights.exposure, global.exposure, "exposure")
        assertNotPinned(weights.noiseArtifacts, global.noiseArtifacts, "noiseArtifacts")
        assertNotPinned(weights.resolution, global.resolution, "resolution")
    }

    private func movementExample(index: Int) -> BestShotOverrideExample {
        BestShotOverrideExample(
            recordedAt: Date(timeIntervalSince1970: Double(index)),
            clusterHasFaces: true,
            componentDelta: PhotoQualityScoringConfig.Weights(
                sharpness: 0.005,
                faceQuality: 0.01,
                exposure: 0,
                noiseArtifacts: 0,
                resolution: 0
            ),
            offsetDelta: 0,
            scoringModelVersion: global.scoringModelVersion
        )
    }

    private func makeExample(
        hasFaces: Bool,
        sharpnessDelta: Double,
        index: Int
    ) -> BestShotOverrideExample {
        BestShotOverrideExample(
            recordedAt: Date(timeIntervalSince1970: Double(index)),
            clusterHasFaces: hasFaces,
            componentDelta: PhotoQualityScoringConfig.Weights(
                sharpness: sharpnessDelta,
                faceQuality: hasFaces ? 0.1 : 0,
                exposure: 0,
                noiseArtifacts: 0,
                resolution: 0
            ),
            offsetDelta: 0,
            scoringModelVersion: global.scoringModelVersion
        )
    }

    private func adversarialExampleSets() -> [[BestShotOverrideExample]] {
        let normal = (0..<50).map { makeExample(hasFaces: true, sharpnessDelta: 0.3, index: $0) }
        let allOnes = (0..<50).map { index -> BestShotOverrideExample in
            BestShotOverrideExample(
                recordedAt: Date(timeIntervalSince1970: Double(index)),
                clusterHasFaces: false,
                componentDelta: PhotoQualityScoringConfig.Weights(
                    sharpness: 1, faceQuality: 1, exposure: 1, noiseArtifacts: 1, resolution: 1
                ),
                offsetDelta: 0,
                scoringModelVersion: global.scoringModelVersion
            )
        }
        let allZeros = (0..<50).map { index -> BestShotOverrideExample in
            BestShotOverrideExample(
                recordedAt: Date(timeIntervalSince1970: Double(index)),
                clusterHasFaces: true,
                componentDelta: PhotoQualityScoringConfig.Weights(
                    sharpness: 0, faceQuality: 0, exposure: 0, noiseArtifacts: 0, resolution: 0
                ),
                offsetDelta: 0,
                scoringModelVersion: global.scoringModelVersion
            )
        }
        let withNonFinite = (0..<50).map { index -> BestShotOverrideExample in
            var sharpnessDelta: Double = 0.2
            if index == 5 { sharpnessDelta = .infinity }
            var exposureDelta: Double = 0
            if index == 12 { exposureDelta = .nan }
            var offset: Double = 0
            if index == 20 { offset = .infinity }
            let delta = PhotoQualityScoringConfig.Weights(
                sharpness: sharpnessDelta,
                faceQuality: 0,
                exposure: exposureDelta,
                noiseArtifacts: 0,
                resolution: 0
            )
            return BestShotOverrideExample(
                recordedAt: Date(timeIntervalSince1970: Double(index)),
                clusterHasFaces: false,
                componentDelta: delta,
                offsetDelta: offset,
                scoringModelVersion: global.scoringModelVersion
            )
        }
        let empty: [BestShotOverrideExample] = []
        return [normal, allOnes, allZeros, withNonFinite, empty]
    }

    private func assertValidWeights(
        _ weights: PhotoQualityScoringConfig.Weights,
        file: StaticString = #filePath,
        line: UInt = #line
    ) {
        XCTAssertEqual(weights.total, 1, accuracy: 1e-9, file: file, line: line)
        XCTAssertGreaterThanOrEqual(weights.sharpness, 0, file: file, line: line)
        XCTAssertGreaterThanOrEqual(weights.faceQuality, 0, file: file, line: line)
        XCTAssertGreaterThanOrEqual(weights.exposure, 0, file: file, line: line)
        XCTAssertGreaterThanOrEqual(weights.noiseArtifacts, 0, file: file, line: line)
        XCTAssertGreaterThanOrEqual(weights.resolution, 0, file: file, line: line)
    }

    private func assertWithinBox(
        _ weights: PhotoQualityScoringConfig.Weights,
        of global: PhotoQualityScoringConfig.Weights,
        file: StaticString = #filePath,
        line: UInt = #line
    ) {
        let tolerance = 1e-9
        XCTAssertLessThanOrEqual(weights.sharpness, global.sharpness + 0.15 + tolerance, file: file, line: line)
        XCTAssertGreaterThanOrEqual(weights.sharpness, global.sharpness - 0.15 - tolerance, file: file, line: line)
        XCTAssertLessThanOrEqual(weights.faceQuality, global.faceQuality + 0.15 + tolerance, file: file, line: line)
        XCTAssertGreaterThanOrEqual(weights.faceQuality, global.faceQuality - 0.15 - tolerance, file: file, line: line)
        XCTAssertLessThanOrEqual(weights.exposure, global.exposure + 0.15 + tolerance, file: file, line: line)
        XCTAssertGreaterThanOrEqual(weights.exposure, global.exposure - 0.15 - tolerance, file: file, line: line)
        XCTAssertLessThanOrEqual(weights.noiseArtifacts, global.noiseArtifacts + 0.15 + tolerance, file: file, line: line)
        XCTAssertGreaterThanOrEqual(weights.noiseArtifacts, global.noiseArtifacts - 0.15 - tolerance, file: file, line: line)
        XCTAssertLessThanOrEqual(weights.resolution, global.resolution + 0.15 + tolerance, file: file, line: line)
        XCTAssertGreaterThanOrEqual(weights.resolution, global.resolution - 0.15 - tolerance, file: file, line: line)
    }

    private func distance(
        _ lhs: PhotoQualityScoringConfig.Weights,
        _ rhs: PhotoQualityScoringConfig.Weights
    ) -> Double {
        sqrt(
            pow(lhs.sharpness - rhs.sharpness, 2)
                + pow(lhs.faceQuality - rhs.faceQuality, 2)
                + pow(lhs.exposure - rhs.exposure, 2)
                + pow(lhs.noiseArtifacts - rhs.noiseArtifacts, 2)
                + pow(lhs.resolution - rhs.resolution, 2)
        )
    }
}
